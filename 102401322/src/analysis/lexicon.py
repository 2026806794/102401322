ALL_LEXICONS = {
    "product": PRODUCT_LEXICON,
    "domain": DOMAIN_LEXICON,
    "sentiment": SENTIMENT_LEXICON,
    "cost": COST_LEXICON,
    "risk": RISK_LEXICON,
}


def iter_patterns(lexicons=None):
    """把词典展开成 (别名, 标准名) 的列表，直接喂给 Aho-Corasick 用。

    例：
        patterns = iter_patterns({"product": PRODUCT_LEXICON})
        ac = AhoCorasick(patterns)
    """
    if lexicons is None:
        lexicons = ALL_LEXICONS

    patterns = []
    for lexicon in lexicons.values():
        for canonical, aliases in lexicon.items():
            for alias in aliases:
                patterns.append((alias, canonical))
    return patterns
